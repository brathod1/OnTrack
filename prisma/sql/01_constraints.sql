-- ── Why they moved ─────────────────────────────────────────────────────────
-- Run as a separate step, a fresh environment gets the tables but not the
-- constraints, and nothing tells you. `prisma migrate deploy` on a new staging
-- or production database would produce a schema that looks right and silently
-- lacks the single-running-timer index — which is the difference between a
-- trustworthy timer and a race condition.
--
-- Keeping a second copy here would invite the two to drift apart, so this file
-- is a pointer rather than a duplicate.
--
-- ── What's in there ────────────────────────────────────────────────────────
--   1. Extensions            btree_gist, pg_trgm
--   2. Timer safety          uniq_running_timer_per_user (partial unique index)
--                            no_overlapping_timer_sessions (GiST exclusion)
--                            duration/note/start-end CHECK constraints
--   3. Subtask depth         enforce_subtask_depth() trigger, capped at 1 level
--   4. Task invariants       reviewer ≠ assignee, reviewer present in REVIEW,
--                            blocked needs a reason, due ≤ statutory ceiling,
--                            estimates non-negative, cancel needs a reason
--   5. Task keys             task_key_counters + next_task_key() → TSK-2026-00001
--   6. Full-text search      search_vector, its triggers, GIN and trigram indexes
--   7. Partial indexes       open tasks, overdue, blocked, running timers
--
-- ── Adding constraints later ───────────────────────────────────────────────
-- Do NOT edit the applied migration — it is history, and editing it breaks the
-- checksum for every environment that has already run it. Instead:
--
